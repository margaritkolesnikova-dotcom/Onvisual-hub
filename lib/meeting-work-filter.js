// ONVISUAL reports are operational documents, not descriptions of personal lives,
// participant emotions or small talk. Preserve objective project facts and tasks.
const personalTitle=/(?:личн.{0,24}(?:вопрос|дел|жизн|обстоятельств|истори|информаци)|семейн|семья|самочувств|здоровье|бытов|small.talk|неформальн|обстановк.{0,18}(?:город|безопасн))/i;
const privateTopics=[
 /\bкак\s+(?:у\s+вас|у\s+тебя|у\s+них)?\s*дела\b/i,
 /личн(?:ая|ые|ую|ой)\s+(?:информаци|жизн|обстоятельств|истори|вопрос)/i,
 /(?:самочувств|болезн|заболел|день\s+рождени|семейн(?:ая|ые)|родственник|беременност)/i,
 /(?:рассказал|поделил(?:ся|ась)|обсудили).{0,40}(?:семь|детях|супруг|жен[еу]|мужа|погод|отпуск)/i,
 /(?:погод|отпуск|праздник).{0,26}(?:как\s+дела|личн|неформальн)/i,
 /(?:ситуаци|обстановк).{0,55}(?:безопасност|городе|воронеж|переезд)/i,
 /(?:безопасност|воронеж).{0,55}(?:ситуаци|обстановк|городе)/i,
 /(?:начали|начался|началась).{0,75}(?:личн|знакомств|неформальн)/i,
 /(?:коротк|неформальн).{0,35}(?:бесед|общени|разговор|вступлен)/i,
 /(?:поделился|рассказал|обсудили).{0,45}(?:личн|семейн|самочувств|как\s+дела)/i
];
const emotions=[
 /(?:выразил|выразила|высказал|высказала|сообщил).{0,46}(?:удовлетворени|довольств|недовольств|возмущени|разочарован)/i,
 /(?:был|была|были|остал(?:ся|ась|ись)|оказал(?:ся|ась)).{0,32}(?:довол|удовлетворен|возмущен|расстроен|обижен)/i,
 /(?:отметил|отметила|сказал|сказала).{0,55}(?:радост|довол|удовлетвор|возмущен|разочарован)/i,
 /(?:похвалил|поблагодарил|порадовал|огорчил|вызвал\s+возмущени|не\s+понравил(?:ся|ось)).{0,52}(?:ответ|объяснен|вопрос|собеседник|встреч|участник)/i,
 /(?:ответами|ответом|объяснениями|объяснением).{0,30}(?:довол|удовлетвор|возмущен|разочарован)/i,
 /(?:переживани|эмоци|настроени).{0,42}(?:участник|спикер|говорящ|сотрудник)/i
];
const nonWorkFiller=[
 /^(?:встреча|созвон|беседа|разговор)\s+(?:начал|началась|началось).{0,75}(?:знакомств|неформальн|личн)/i,
 /^участники?\s+(?:начали|завершили|обменялись).{0,70}(?:приветств|личн|новост|впечатлен|благодарност)/i,
 /^(?:все|команда|участники)\s+(?:поблагодарили|поприветствовали|попрощались)/i,
 /^(?:встреча|совещание|разговор)\s+прошл[ао]\s+(?:хорошо|успешно|приятно)/i
];
export function isPersonalHeading(title){
 return personalTitle.test(String(title||''));
}
export function isNonWorkStatement(text){
 const s=String(text||'').trim();
 if(!s)return true;
 return [...privateTopics,...emotions,...nonWorkFiller].some(pattern=>pattern.test(s));
}
export function workSentences(text){
 const s=String(text||'').replace(/\s+/g,' ').trim();
 if(!s)return [];
 const parts=s.match(/[^.!?]+(?:[.!?]+|$)/g)||[s];
 return parts.map(x=>x.trim()).filter(x=>x.length>9&&!isNonWorkStatement(x));
}
export function cleanWorkParagraph(text){
 return workSentences(text).join(' ').trim();
}
